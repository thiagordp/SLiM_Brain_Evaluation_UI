"""Turn a service-account JSON key into the Streamlit secrets block.

Pasting the key into TOML by hand is the most error-prone step of deployment:
`private_key` is a multi-line PEM that must survive as literal \\n escapes inside
a quoted string. This does that conversion exactly.

    python app/tools/make_secrets.py ~/.config/slim-brain/service-account.json \\
        --sheet-id 1AbC…XyZ

Prints the block to paste into Streamlit Cloud → Advanced settings → Secrets.
Pass --write to save it as .streamlit/secrets.toml for local use instead; that
path is gitignored.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import secrets as secrets_module
import sys

FIELDS = (
    "type", "project_id", "private_key_id", "private_key", "client_email",
    "client_id", "auth_uri", "token_uri", "auth_provider_x509_cert_url",
    "client_x509_cert_url", "universe_domain",
)


def toml_string(value: str) -> str:
    """A TOML basic string: escapes stay escapes, newlines become \\n."""
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("key_file", type=pathlib.Path,
                        help="the downloaded service-account JSON key")
    parser.add_argument("--sheet-id", default="", help="the workbook id from its URL")
    parser.add_argument("--password", default="", help="evaluator password (generated if omitted)")
    parser.add_argument("--admin-secret", default="", help="admin secret (generated if omitted)")
    parser.add_argument("--write", action="store_true",
                        help="save to .streamlit/secrets.toml instead of printing")
    args = parser.parse_args()

    if not args.key_file.exists():
        raise SystemExit(f"no such file: {args.key_file}")
    key = json.loads(args.key_file.read_text(encoding="utf-8"))

    if key.get("type") != "service_account":
        raise SystemExit(
            f"{args.key_file} is not a service-account key "
            f"(type={key.get('type')!r}). Download the JSON key from the service "
            f"account's Keys tab, not an OAuth client id."
        )
    for required in ("client_email", "private_key"):
        if not key.get(required):
            raise SystemExit(f"the key file has no {required}")

    password = args.password or secrets_module.token_urlsafe(12)
    admin = args.admin_secret or secrets_module.token_urlsafe(16)

    lines = [
        "# Streamlit Cloud -> Advanced settings -> Secrets",
        "# Generated by app/tools/make_secrets.py — treat this as a password.",
        "",
        f"HE_APP_PASSWORD   = {toml_string(password)}",
        f"HE_ADMIN_SECRET   = {toml_string(admin)}",
        f"GOOGLE_SHEET_ID   = {toml_string(args.sheet_id)}",
        "HE_REQUIRE_SHEETS = true",
        "",
        "[gcp_service_account]",
    ]
    for field in FIELDS:
        if field in key:
            lines.append(f"{field} = {toml_string(str(key[field]))}")
    block = "\n".join(lines) + "\n"

    if args.write:
        target = pathlib.Path(".streamlit/secrets.toml")
        target.parent.mkdir(exist_ok=True)
        target.write_text(block, encoding="utf-8")
        target.chmod(0o600)
        print(f"wrote {target} (gitignored, mode 600)")
    else:
        print(block)

    print("Service account:", key["client_email"], file=sys.stderr)
    print("Share the sheet with that address as an Editor.", file=sys.stderr)
    if not args.sheet_id:
        print("WARNING: no --sheet-id given; fill GOOGLE_SHEET_ID in before deploying.",
              file=sys.stderr)
    if not args.password:
        print(f"Generated evaluator password: {password}", file=sys.stderr)
    if not args.admin_secret:
        print(f"Generated admin secret: {admin}", file=sys.stderr)


if __name__ == "__main__":
    main()
