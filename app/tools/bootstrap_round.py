"""Initialise a fresh Google Sheets workbook for one evaluation round.

One round = one workbook. Given

    GOOGLE_SHEET_ID + service account     a new, empty workbook
    app/data/round.yaml                   the round id and its allocation
    brain/                                the Brain snapshot
    app/data/manifest.yaml                generated by build_assignments.py

this validates everything first — preflight, allocation, manifest freshness —
and only then creates every tab with its exact headers, writes the round's
self-describing metadata (ROUND, DEFINITIONS), the configuration (CONFIG,
EVALUATORS, ASSIGNMENTS), and preallocates every review block.

    python app/tools/bootstrap_round.py --dry-run
    python app/tools/bootstrap_round.py
    python app/tools/bootstrap_round.py --extend                 # add new assignments
    python app/tools/bootstrap_round.py --overwrite-round ROUND-2026-01

It refuses a workbook that already holds anything other than blank default
sheets. An interrupted bootstrap is replaced with `--overwrite-round PARTIAL`. `--overwrite-round` names the round it may replace, and if any evaluator
has already worked in it, `--discard-evaluations` must be given as well.
`--extend` adds reviews for assignments not yet present in the same round (for
example a newly added Source) and never touches existing rows; it requires the
same Brain snapshot, instrument and definitions as the round.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import pathlib
import subprocess
import sys

APP = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(APP))

import allocation  # noqa: E402
import manifest  # noqa: E402
import preflight  # noqa: E402
import progress  # noqa: E402
import sheets  # noqa: E402
import spec  # noqa: E402
import store  # noqa: E402
from brain import load_brain  # noqa: E402

TOOL = "app/tools/bootstrap_round.py"
PLACEHOLDER = "_bootstrap"
#: What an interrupted bootstrap leaves: round tabs without a recorded round.
PARTIAL = "PARTIAL"


class BootstrapRefused(RuntimeError):
    pass


def _git_commit() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=APP,
                              capture_output=True, text=True, check=True).stdout.strip()
    except Exception:
        return ""


def validate_inputs(brain) -> tuple[dict, list[str]]:
    """The manifest, and every reason it may not be bootstrapped."""
    problems = []
    report = preflight.check(brain)
    problems += [f"preflight: {e}" for e in report.errors]

    path = manifest.allocation_path()
    data = allocation.load(path)
    problems += [f"allocation: {p}" for p in allocation.validate(data, brain)]

    doc = manifest.load_manifest_file()
    meta = doc.get("round") or {}
    expected = {
        "round_id": manifest.round_id(),
        "allocation_sha256": allocation.digest(path),
        "brain_snapshot_id": brain.snapshot_id,
        "eval_spec_version": spec.EVAL_SPEC_VERSION,
        "definitions_id": spec.definitions_id(),
    }
    for key, value in expected.items():
        if str(meta.get(key, "")) != str(value):
            problems.append(
                f"manifest: {key} is {meta.get(key)!r}, expected {value!r} — run "
                f"`python app/tools/build_assignments.py` to regenerate it")
    return doc, problems


def plan_rows(brain, doc: dict, round_id: str) -> tuple[list[dict], dict]:
    names = {e["evaluator_id"]: e for e in doc["evaluators"]}
    reviews, blocks = [], {}
    for row in doc["assignments"]:
        rid = store.review_id(round_id, row["phase_id"], row["evaluator_id"],
                              row["source_id"])
        evaluator = names.get(row["evaluator_id"], {})
        reviews.append({
            "review_id": rid, "round_id": round_id, "phase_id": row["phase_id"],
            "evaluator_id": row["evaluator_id"],
            "evaluator_name": evaluator.get("name", row["evaluator_id"]),
            "pair_id": evaluator.get("pair_id", ""), "source_id": row["source_id"],
            "assignment_key": row["assignment_key"], "split_id": row["split_id"],
            "pdf_read_confirmed": 0, "status": store.STATUS_NOT_STARTED,
        })
        blocks[rid] = progress.review_rows(brain, rid, row["source_id"])
    return reviews, blocks


def round_rows(brain, doc: dict, round_id: str) -> list[dict]:
    meta = doc["round"]
    values = {
        "round_id": round_id,
        "eval_spec_version": spec.EVAL_SPEC_VERSION,
        "definitions_id": spec.definitions_id(),
        "brain_snapshot_id": brain.snapshot_id,
        "brain_canonical_schema_version": brain.canonical_schema_version,
        "brain_runs": json.dumps(brain.run_schema_versions(), sort_keys=True),
        "schema_source_hashes": json.dumps(spec.frozen_source_hashes(), sort_keys=True),
        "allocation_id": meta["allocation_id"],
        "allocation_status": meta["allocation_status"],
        "allocation_file": meta["allocation_file"],
        "allocation_sha256": meta["allocation_sha256"],
        "created_at": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
        "created_by": TOOL,
        "app_commit": _git_commit(),
    }
    return [{"key": k, "value": str(v)} for k, v in values.items()]


def definition_rows() -> list[dict]:
    out = []
    for key, entry in sorted(spec.definitions()["entries"].items()):
        out.append({"key": key, "label": entry["label"], "source_file": entry["source"],
                    "text": entry.get("text", ""),
                    "items_json": json.dumps(entry.get("items", []), ensure_ascii=False)})
    # Calibration guidance is recorded too, so the workbook describes everything
    # evaluators were shown — under its own keys and source, never as schema text.
    for key, lines in sorted(spec.CALIBRATION.items()):
        out.append({"key": f"calibration.{key}", "label": "Calibration",
                    "source_file": spec.CALIBRATION_SOURCE, "text": "\n\n".join(lines),
                    "items_json": "[]"})
    return out


def inspect(book) -> dict:
    """What the workbook holds now."""
    titles = book.tab_titles()
    ours = [t for t in titles if t in sheets.ALL_TABS]
    foreign = [t for t in titles if t not in sheets.ALL_TABS]
    existing_round = ""
    started = []
    if sheets.ROUND in ours:
        existing_round = {r["key"]: r["value"] for r in book.read_tab(sheets.ROUND)
                          }.get("round_id", "")
    if sheets.REVIEWS in ours:
        started = [r["review_id"] for r in book.read_tab(sheets.REVIEWS)
                   if manifest.has_activity(r)]
    blank_foreign = [t for t in foreign if book.is_blank(t)]
    return {"titles": titles, "ours": ours, "foreign": foreign,
            "blank_foreign": blank_foreign, "round": existing_round,
            "started": started}


def create_tabs(book) -> None:
    present = set(book.tab_titles())
    for tab in sheets.ALL_TABS:
        if tab not in present:
            book.create_tab(tab)
        book.write_header(tab)


def verify_blocks(book, round_id: str) -> list[str]:
    """Read back the first and last key of every block: the ranges must be true."""
    problems = []
    reviews = [r for r in book.read_tab(sheets.REVIEWS) if r["round_id"] == round_id]
    requests, expect = [], []
    for review in reviews:
        for tab in sheets.BLOCK_TABS:
            prefix = sheets.BLOCK_PREFIX[tab]
            first = review.get(f"{prefix}_first_row")
            last = review.get(f"{prefix}_last_row")
            if first and last:
                requests += [(tab, int(first), int(first)), (tab, int(last), int(last))]
                expect += [(review["review_id"], tab, first), (review["review_id"], tab, last)]
    for (rid, tab, row), rows in zip(expect, book.read_ranges(requests)):
        if not rows or rows[0].get("review_id") != rid:
            problems.append(f"{tab} row {row} does not belong to {rid}")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dry-run", action="store_true",
                        help="validate and report; write nothing")
    parser.add_argument("--extend", action="store_true",
                        help="add reviews for new assignments to this round")
    parser.add_argument("--overwrite-round", metavar="ROUND_ID",
                        help="replace the round stored in the workbook (must name it)")
    parser.add_argument("--discard-evaluations", action="store_true",
                        help="with --overwrite-round: allowed even if work has started")
    args = parser.parse_args()

    brain = load_brain()
    round_id = manifest.round_id()
    doc, problems = validate_inputs(brain)
    if problems:
        print("Refusing to bootstrap; nothing was written:")
        for problem in problems:
            print(f"  - {problem}")
        return 1

    reviews, blocks = plan_rows(brain, doc, round_id)
    totals = {tab: sum(len(b[tab]) for b in blocks.values()) for tab in sheets.BLOCK_TABS}
    print(f"round {round_id} · spec {spec.EVAL_SPEC_VERSION} · definitions "
          f"{spec.definitions_id()} · snapshot {brain.short_snapshot}")
    print(f"allocation {doc['round']['allocation_id']} "
          f"({doc['round']['allocation_status']}) · {len(doc['evaluators'])} evaluators "
          f"· {len(doc['assignments'])} assignments")
    print(f"rows: {len(reviews)} reviews, "
          + ", ".join(f"{n} {tab}" for tab, n in totals.items()))
    if args.dry_run and not sheets.configured():
        print("dry run: no workbook configured, so its state was not inspected")
        return 0

    try:
        book = store.workbook()
        state = inspect(book)
    except sheets.StorageError as error:
        print(f"Cannot use the workbook: {error}")
        return 1

    try:
        if args.extend:
            if state["round"] != round_id:
                raise BootstrapRefused(
                    f"--extend needs round {round_id} in the workbook; it holds "
                    f"{state['round'] or 'no round'}")
            stored = store.round_metadata()
            for key in ("eval_spec_version", "definitions_id", "brain_snapshot_id"):
                current = {"eval_spec_version": spec.EVAL_SPEC_VERSION,
                           "definitions_id": spec.definitions_id(),
                           "brain_snapshot_id": brain.snapshot_id}[key]
                if stored.get(key) != current:
                    raise BootstrapRefused(
                        f"--extend: the round was bootstrapped with {key} "
                        f"{stored.get(key)!r}, not {current!r}. A changed Brain or "
                        f"instrument is a new round in a new workbook.")
        else:
            occupied = [t for t in state["foreign"] if t not in state["blank_foreign"]]
            if occupied:
                raise BootstrapRefused(
                    f"the workbook holds tabs that are not part of a round "
                    f"({', '.join(occupied)}). Use a new, empty workbook.")
            if state["ours"]:
                held = state["round"] or PARTIAL
                if args.overwrite_round != held:
                    raise BootstrapRefused(
                        f"the workbook already holds round {held}. It is replaced only "
                        f"with --overwrite-round {held}.")
                if state["started"] and not args.discard_evaluations:
                    raise BootstrapRefused(
                        f"{len(state['started'])} review(s) in round {held} have "
                        f"evaluator activity. Replacing the round discards them; add "
                        f"--discard-evaluations only if that is intended.")
    except BootstrapRefused as refusal:
        print(f"Refusing to bootstrap; nothing was written: {refusal}")
        return 1

    if args.dry_run:
        print("dry run: the workbook would be accepted; nothing was written")
        return 0

    if not args.extend:
        # A workbook must always keep one tab, so the old ones are removed behind
        # a placeholder that is itself removed once the round's tabs exist.
        if PLACEHOLDER not in book.tab_titles():
            book.create_tab(PLACEHOLDER)
        for title in book.tab_titles():
            if title != PLACEHOLDER:
                book.delete_tab(title)
        store.forget_all()
        create_tabs(book)
        book.delete_tab(PLACEHOLDER)
        book.append_rows(sheets.ROUND, round_rows(brain, doc, round_id))
        book.append_rows(sheets.DEFINITIONS, definition_rows())
        book.append_rows(sheets.CONFIG, [{"key": k, "value": v}
                                         for k, v in doc["config"].items()])
        book.append_rows(sheets.EVALUATORS, doc["evaluators"])
        book.append_rows(sheets.ASSIGNMENTS, doc["assignments"])
    else:
        present = {r["assignment_key"] for r in book.read_tab(sheets.ASSIGNMENTS)}
        book.append_rows(sheets.ASSIGNMENTS, [a for a in doc["assignments"]
                                              if a["assignment_key"] not in present])
        known = {r["evaluator_id"] for r in book.read_tab(sheets.EVALUATORS)}
        book.append_rows(sheets.EVALUATORS, [e for e in doc["evaluators"]
                                             if e["evaluator_id"] not in known])

    store.forget_all()
    made = store.preallocate(reviews, blocks)
    print("created: " + ", ".join(f"{v} {k}" for k, v in made.items()))
    problems = verify_blocks(book, round_id)
    if problems:
        print("VERIFICATION FAILED — the recorded row ranges do not match the rows:")
        for problem in problems[:20]:
            print(f"  - {problem}")
        return 1
    print(f"verified: every review block of {round_id} reads back at its recorded rows")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
