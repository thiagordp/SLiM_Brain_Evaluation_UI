"""Generate the explicit runtime manifest from the allocation file.

The one supported allocation path:

    data/allocation/<round>.yaml   human-editable: pairs, splits, Sources
            |  python app/tools/build_assignments.py      (validates)
    data/manifest.yaml             explicit evaluator x Source x phase rows
            |  python app/tools/bootstrap_round.py
    the round workbook

Nothing here encodes an allocation. Replacing the development allocation with
the accepted one — or adding the 26th Source — is an edit to the allocation
file followed by a rerun of this tool.

    python app/tools/build_assignments.py              # validate and write
    python app/tools/build_assignments.py --dry-run    # validate and summarise
    python app/tools/build_assignments.py --allocation PATH
"""
from __future__ import annotations

import argparse
import collections
import pathlib
import sys

import yaml

APP = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(APP))

import allocation  # noqa: E402
import manifest  # noqa: E402
import spec  # noqa: E402
from brain import load_brain  # noqa: E402

HEADER = """\
# Runtime manifest — GENERATED by app/tools/build_assignments.py. Do not edit.
#
# Edit the allocation file named under `round.allocation_file` instead, then
# regenerate. Every evaluator x Source x phase assignment is an explicit row;
# the application never infers one from a pair or split name.
"""


def build(path: pathlib.Path) -> dict:
    brain = load_brain()
    data = allocation.load(path)
    problems = allocation.validate(data, brain)
    if problems:
        raise allocation.AllocationError(problems)
    evaluators, assignments = allocation.expand(data, brain)
    return {
        "round": {
            "round_id": manifest.round_id(),
            "allocation_id": str(data["allocation_id"]),
            "allocation_status": str(data["status"]),
            "allocation_file": path.relative_to(manifest.DATA).as_posix()
            if path.is_relative_to(manifest.DATA) else str(path),
            "allocation_sha256": allocation.digest(path),
            "brain_snapshot_id": brain.snapshot_id,
            "eval_spec_version": spec.EVAL_SPEC_VERSION,
            "definitions_id": spec.definitions_id(),
        },
        "config": {"training_open": "true", "agreement_open": "true",
                   "individual_open": "true"},
        "evaluators": evaluators,
        "assignments": assignments,
    }


def summary(result: dict) -> str:
    rows = result["assignments"]
    lines = [f"round {result['round']['round_id']} · allocation "
             f"{result['round']['allocation_id']} ({result['round']['allocation_status']})"]
    by_phase = collections.Counter((r["phase_id"], r["assignment_state"]) for r in rows)
    for (phase, state), count in sorted(by_phase.items()):
        papers = len({r["source_id"] for r in rows
                      if r["phase_id"] == phase and r["assignment_state"] == state})
        lines.append(f"  {phase:<11} {state:<9} {count:>3} rows over {papers} papers")
    per_eval = collections.Counter(r["evaluator_id"] for r in rows
                                   if r["phase_id"] == allocation.INDIVIDUAL
                                   and r["assignment_state"] == allocation.ASSIGNED)
    lines.append("  individual papers per evaluator: "
                 + ", ".join(f"{k} {v}" for k, v in sorted(per_eval.items())))
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--allocation", type=pathlib.Path,
                        default=manifest.allocation_path())
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    try:
        result = build(args.allocation.resolve())
    except allocation.AllocationError as error:
        print("The allocation is invalid; nothing was written:")
        for problem in error.problems:
            print(f"  - {problem}")
        return 1
    print(summary(result))
    if args.dry_run:
        return 0
    out = manifest.manifest_path()
    out.write_text(HEADER + yaml.safe_dump(result, sort_keys=False, allow_unicode=True),
                   encoding="utf-8")
    print(f"wrote {out.relative_to(APP.parent)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
